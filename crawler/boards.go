package crawler

import "strings"

// CanonicalBoard returns the official case-sensitive board name for PTT
func CanonicalBoard(board string) string {
	bLower := strings.ToLower(strings.TrimSpace(board))
	if canon, ok := canonicalBoards[bLower]; ok {
		return canon
	}
	// Fallback: Capitalize first letter
	if len(board) > 0 {
		return strings.ToUpper(board[:1]) + strings.ToLower(board[1:])
	}
	return board
}

